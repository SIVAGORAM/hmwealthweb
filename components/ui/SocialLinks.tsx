/** Social media icons. All six always show; any network without a URL in `socials` (lib/site.ts)
 *  renders as a non-clickable icon until its link is added. WhatsApp uses the business number. */
export function SocialLinks({ className, size = "md" }: { className?: string; size?: "sm" | "md" }) {
  const urls: Record<Network, string> = { ...socials, whatsapp: site.whatsappHref };
  const items = NETWORKS;
  return (
    <ul className={cn("flex flex-wrap items-center gap-2", className)} aria-label={`${site.name} on social media`}>
      {items.map((n) => (
        <li key={n.key}>
          <a
            {...(urls[n.key]
              ? { href: urls[n.key], target: "_blank", rel: "noopener noreferrer" }
              : { "aria-disabled": true })}
            aria-label={`${site.name} on ${n.label}`}
            title={n.label}
            className={cn(
              "flex items-center justify-center rounded-xl bg-white text-brand ring-1 ring-line shadow-[0_1px_2px_rgba(20,24,30,0.05)] transition duration-200 hover:-translate-y-0.5 hover:shadow-[0_10px_20px_-12px_rgba(20,24,30,0.35)] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand",
              size === "sm" ? "size-9" : "size-10",
              n.hover
            )}
          >
            <svg viewBox="0 0 24 24" fill="currentColor" className={size === "sm" ? "size-4" : "size-[18px]"} aria-hidden>
              <path d={paths[n.key]} />
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
